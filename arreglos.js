// push=>agregar al final
// sirve para agregar al final del arreglo
let lista = []
lista.push("a")
console.log(lista)
lista.push("b")
console.log(lista)

// unshift: agregar al inicio del arreglo
lista.unshift("c")
console.log(lista)

// pop sirve para eliminar elementos al final
lista.pop()
console.log(lista)

// shift elimina al inicio
lista.shift()
console.log(lista)